        if (Find(number) is not { } lesson) return "";
        return $"""
            METOD
            {lesson.Method}

            O‘QUV NATIJASI
            {lesson.Goal}

            DARS UCHUN TAYYORGARLIK
            {lesson.Setup} Internet cheklanganida oldindan saqlangan yoki bosma namunalardan foydalanish mumkin.

            MASHG‘ULOT TARTIBI · 2 AKADEMIK SOAT
            1. Kirish · 10 daqiqa — {lesson.Introduction}
            2. Namoyish · 20 daqiqa — {lesson.Demonstration}
            3. Mashq · 45 daqiqa — {lesson.Activity}
            4. Muhokama va tekshiruv · 15 daqiqa — {lesson.Assessment}

            YAKUNIY ISH VA BAHOLASH MEZONI
            {lesson.Evidence}
            """;
    }

    internal static Lesson? Find(int number) => number >= 1 && number <= Lessons.Length ? Lessons[number - 1] : null;
